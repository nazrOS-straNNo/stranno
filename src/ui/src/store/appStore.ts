import { create } from "zustand";

export type МодульИд =
  | "путь" | "проекты" | "миры" | "сцены"
  | "руки" | "мульт" | "яблочко" | "точки"
  | "глюк" | "студия" | "поле" | "шина"
  | "колодец" | "библиотека" | "лавка" | "клуб";

export type Тема = "тёмная" | "светлая";

export interface СтатусЯдра {
  стабильно: boolean;
  памятьПроцент: number;
  fps: number;
  автосохранениеМинутНазад: number | null;
}

export interface АппСтейт {
  активныйМодуль: МодульИд;
  ядро: СтатусЯдра;
  имяПользователя: string;
  рольПользователя: string;
  показатьПомощьКлавиш: boolean;
  масштабUI: number;
  тема: Тема;
  авторизован: boolean;

  переключитьМодуль: (модуль: МодульИд) => void;
  обновитьСтатусЯдра: (статус: Partial<СтатусЯдра>) => void;
  переключитьПомощьКлавиш: () => void;
  установитьМасштаб: (м: number) => void;
  переключитьТему: () => void;
  войти: () => void;
  выйти: () => void;
}

export const useAppStore = create<АппСтейт>((set) => ({
  активныйМодуль: "руки",
  ядро: {
    стабильно: true,
    памятьПроцент: 72,
    fps: 120,
    автосохранениеМинутНазад: 2,
  },
  имяПользователя: "AJNA",
  рольПользователя: "инженер миров",
  показатьПомощьКлавиш: false,
  масштабUI: 1,
  тема: "тёмная",
  авторизован: false,

  переключитьМодуль: (модуль) => set({ активныйМодуль: модуль }),
  обновитьСтатусЯдра: (статус) =>
    set((s) => ({ ядро: { ...s.ядро, ...статус } })),
  переключитьПомощьКлавиш: () =>
    set((s) => ({ показатьПомощьКлавиш: !s.показатьПомощьКлавиш })),
  установитьМасштаб: (м) => set({ масштабUI: м }),
  переключитьТему: () =>
    set((s) => ({ тема: s.тема === "тёмная" ? "светлая" : "тёмная" })),
  войти: () => set({ авторизован: true }),
  выйти: () => set({ авторизован: false }),
}));
